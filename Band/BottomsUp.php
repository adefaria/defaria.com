      <p>When asked the question, "What new talent is sweeping through the Bay Area club scene?", the band <b>Bottoms Up</b> quickly comes to mind. Former <a href="/Band/index.php">Cast of Shadows</a> members Andy DeFaria and Scott Dinn teamed up with Steve Burgio and with Steve Sampson of <i>The Wave</i> to form this high-energy modern rock dance band.</p>

      <p>With each member boasting over 10 years of stage experience and a list of credentials surpassing most local cover acts, the fan base was strong and growing. Sampson's success in <i>The Wave</i> earned him credit as a supporting act for national artists such as Richard Marx, Bad English, and The Tubes. On the home front, DeFaria and Dinn performed steadily throughout the Bay Area as leading members of the well-established <i>Cast of Shadows</i>.</p>

